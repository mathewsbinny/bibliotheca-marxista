#!/usr/bin/env node
/**
 * Records each publishing house's identifiers (identifiers: Wikidata, VIAF, the Library of
 * Congress, the GND, ISNI, the BnF) in data/publishers/<id>.yaml, for the site's linked data.
 *
 * The house's Wikidata item is the one its file records or links (a Wikidata or Wikipedia source),
 * else the one found by its names and country, as scripts/check-publisher-years.mjs finds it.
 *
 *   node scripts/link-publishers.mjs           report only (reports/publisher-identifiers.md)
 *   node scripts/link-publishers.mjs --write   also write the identifiers
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import * as yaml from 'js-yaml';
import { ROOT } from './lib/openlibrary.mjs';
import { entity, findEntity, getJson, identifiersOf, withIdentifiers } from './lib/wikidata.mjs';

const PUBLISHERS = join(ROOT, 'data', 'publishers');
const WRITE = process.argv.includes('--write');

/** The item a Wikipedia article is about. */
async function articleItem(url) {
  const m = /^https:\/\/([a-z-]+)\.wikipedia\.org\/wiki\/([^#?]+)/.exec(url ?? '');
  if (!m) return undefined;
  const title = decodeURIComponent(m[2]).replace(/_/g, ' ');
  const r = await getJson(`https://${m[1]}.wikipedia.org/w/api.php?action=query&format=json&prop=pageprops&ppprop=wikibase_item&redirects=1&titles=${encodeURIComponent(title)}`);
  return Object.values(r.query?.pages ?? {})[0]?.pageprops?.wikibase_item;
}

async function itemOf(p) {
  if (p.identifiers?.wikidata) return [p.identifiers.wikidata, 'recorded'];
  const linked = JSON.stringify(p.sources ?? []).match(/wikidata\.org\/wiki\/(Q\d+)/)?.[1];
  if (linked) return [linked, 'linked'];
  for (const s of p.sources ?? []) {
    const qid = await articleItem(s.url);
    if (qid) return [qid, 'Wikipedia'];
  }
  const e = await findEntity(p);
  return e ? [e.id, 'searched'] : [];
}

const rows = [];
let n = 0;
const files = readdirSync(PUBLISHERS).filter((f) => f.endsWith('.yaml')).sort();
for (const f of files) {
  const file = join(PUBLISHERS, f);
  const text = readFileSync(file, 'utf8');
  const p = yaml.load(text);
  const [qid, how] = await itemOf(p).catch((err) => (console.warn(`${p.name}: ${err.message}`), []));
  if (++n % 50 === 0) console.log(`${n}/${files.length}`);
  if (!qid) { rows.push(`| ${p.name} | — | | |`); continue; }
  const e = await entity(qid).catch(() => undefined);
  if (!e) { rows.push(`| ${p.name} | ${qid} (not found) | | |`); continue; }
  const found = identifiersOf(qid, e);
  rows.push(`| ${p.name} | [${qid}](https://www.wikidata.org/wiki/${qid}) | ${how} | ${Object.keys(found).filter((k) => k !== 'wikidata').join(', ') || '—'} |`);
  if (WRITE) writeFileSync(file, withIdentifiers(text, found));
}

const linked = rows.filter((r) => !/\| — \| \| \|$/.test(r)).length;
mkdirSync(join(ROOT, 'reports'), { recursive: true });
writeFileSync(join(ROOT, 'reports', 'publisher-identifiers.md'), [
  '# Publishers\' identifiers', '', `Generated by scripts/link-publishers.mjs: ${linked} of ${files.length} houses have a Wikidata item.`, '',
  '| House | Wikidata | Found by | Other identifiers |', '|---|---|---|---|', ...rows, '',
].join('\n'));
console.log(`${linked} of ${files.length} houses have a Wikidata item. See reports/publisher-identifiers.md`);
